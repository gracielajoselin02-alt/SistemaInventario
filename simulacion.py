import numpy as np
import matplotlib.pyplot as plt

t = np.linspace(0, 2, 2000)
pulso = ((t >= 0.4) & (t < 0.6)).astype(float)
escalon = (t >= 1).astype(float)
seno = np.sin(2*np.pi*50*t)

senales = [pulso, escalon, seno]
nombres = ["Pulso rectangular", "Escalon", "Senoidal"]

fig, ejes = plt.subplots(3, 3, figsize=(12, 9))

for i in range(3):
    x = senales[i]
    X = np.fft.fft(x)
    f = np.fft.fftfreq(len(x), t[1]-t[0])
    orden = np.argsort(f)

    ejes[i, 0].plot(t, x)
    ejes[i, 0].set_title(nombres[i] + " - Tiempo")

    ejes[i, 1].plot(f[orden], np.abs(X[orden])/len(x))
    ejes[i, 1].set_xlim(0, 150)
    ejes[i, 1].set_title("Magnitud")

    ejes[i, 2].plot(f[orden], np.angle(X[orden]))
    ejes[i, 2].set_xlim(0, 150)
    ejes[i, 2].set_title("Fase")

plt.tight_layout()
plt.show()

print("Simulacion terminada")